import {
  pgTable, uuid, integer, timestamp, unique,
  text, boolean, jsonb, type AnyPgColumn, real, index,
} from 'drizzle-orm/pg-core'

// ── Brands ───────────────────────────────────────────────────────────────────

export const brands = pgTable('brands', {
  id: uuid('id').primaryKey().defaultRandom(),
  userId: uuid('user_id').notNull(),
  name: text('name').notNull(),
  websiteUrl: text('website_url').notNull(),
  keywords: text('keywords'), // comma-separated brand keywords/tags
  industry: text('industry'),
  targetAudience: text('target_audience'),
  usp: text('usp'),
  brandVoice: text('brand_voice'),
  logoUrl: text('logo_url'),
  themeColor: text('theme_color'),
  playbook: jsonb('playbook'),   // PlaybookData — generated by Foundation analysis, editable by user
  analyticsSnapshot: jsonb('analytics_snapshot'),         // cached /api/analytics/auth-dashboard response
  analyticsSnapshotAt: timestamp('analytics_snapshot_at', { withTimezone: true }), // when cache was last saved
  analyticsCardOverrides: jsonb('analytics_card_overrides'), // per-card label/event overrides for built-in Type B cards
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
})

// ── Competitor Registry (centralized across all modules) ──────────────────

export const competitors = pgTable(
  'competitors',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    brandId: uuid('brand_id').notNull().references(() => brands.id, { onDelete: 'cascade' }),
    url: text('url').notNull(),
    name: text('name'), // e.g. "Buffer", "Hootsuite"
    type: text('type'), // 'direct' | 'indirect' | 'aspirational' — competitor classification
    marketPosition: text('market_position'), // 'leader' | 'challenger' | 'niche_player' | 'new_entrant'
    primaryStrength: text('primary_strength'), // main competitive advantage observed
    discoveredIn: text('discovered_in'), // module type that discovered it (e.g. 'competitor-analysis')
    discoveredAt: timestamp('discovered_at', { withTimezone: true }).defaultNow(),
    lastAnalyzedAt: timestamp('last_analyzed_at', { withTimezone: true }),
  },
  (table) => ({
    uniq: unique('competitors_unique').on(table.brandId, table.url),
  }),
)

// ── Modules ──────────────────────────────────────────────────────────────────

export const modules = pgTable('modules', {
  id: uuid('id').primaryKey().defaultRandom(),
  brandId: uuid('brand_id').notNull().references(() => brands.id, { onDelete: 'cascade' }),
  type: text('type').notNull(),           // 'foundation' | 'seo' | 'social_media' | ...
  name: text('name').notNull(),
  order: integer('order').notNull(),      // 0 = Foundation, 1 = SEO, 2 = Social, ...
  status: text('status').notNull().default('locked'), // 'locked'|'pending'|'analyzing'|'complete'
  requirements: jsonb('requirements'),    // { website_url: "https://..." }
  score: integer('score').default(0),     // 0-100 completion %
  lastAnalyzedAt: timestamp('last_analyzed_at', { withTimezone: true }),
  agentBranch: text('agent_branch'),      // shared GitHub branch for this module's fixes
  agentPrUrl: text('agent_pr_url'),       // GitHub PR URL for the shared fixes branch
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
})

// ── Module Categories (self-referential for sub-categories) ──────────────────

export const moduleCategories = pgTable('module_categories', {
  id: uuid('id').primaryKey().defaultRandom(),
  moduleId: uuid('module_id').notNull().references(() => modules.id, { onDelete: 'cascade' }),
  parentId: uuid('parent_id').references((): AnyPgColumn => moduleCategories.id, { onDelete: 'cascade' }),
  slug: text('slug').notNull(),
  label: text('label').notNull(),
  order: integer('order').notNull(),
})

// ── Module Items (actionable checklist items) ─────────────────────────────────

export const moduleItems = pgTable(
  'module_items',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    moduleId: uuid('module_id').notNull().references(() => modules.id, { onDelete: 'cascade' }),
    categoryId: uuid('category_id').notNull().references(() => moduleCategories.id, { onDelete: 'cascade' }),
    slug: text('slug').notNull(),
    label: text('label').notNull(),
    weight: integer('weight').notNull().default(1), // 1=minor | 2=important | 3=critical
    aiDetail: text('ai_detail'),           // one-line finding (always shown)
    aiHighlight: text('ai_highlight'),     // 5–8 word key phrase (shown expanded, prominent)
    aiNarrative: text('ai_narrative'),     // 1-sentence context (expandable)
    aiAction: text('ai_action'),           // specific next step (expandable)
    aiVerified: boolean('ai_verified').default(false),
    aiVerifiedAt: timestamp('ai_verified_at', { withTimezone: true }),
    userChecked: boolean('user_checked').default(false),
    userCheckedAt: timestamp('user_checked_at', { withTimezone: true }),
    completedBy: text('completed_by'),     // 'ai' | 'user' | 'agent' | null
    fixable: boolean('fixable').default(false), // true = Claude can auto-fix via GitHub
    fixType: text('fix_type'),                             // 'template' | 'value' | 'patch' | null (null = legacy full-file flow)
    fixInputKey: text('fix_input_key'),                    // metadata key to read from brandIntegrations (e.g. 'ga4_measurement_id')
    fixIntegrationProvider: text('fix_integration_provider'), // which integration to read from (e.g. 'google_analytics')
    aiDraft: text('ai_draft'),             // on-demand AI-generated draft content (copy, outline, template)
    aiData: jsonb('ai_data'),              // structured data payload (e.g. calendar entries JSON for content-calendar-30-day)
    userSkipped: boolean('user_skipped').default(false),
    userSkipReason: text('user_skip_reason'),
    exportType: text('export_type'),           // 'auto' | 'needs_choice' | 'external' | null
    choiceOptions: jsonb('choice_options'),     // string[] | null — AI-generated options for modal
    userChoice: text('user_choice'),            // chosen value from modal (null until user picks)
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
  },
  (table) => ({
    uniq: unique('module_item_unique').on(table.moduleId, table.slug),
  }),
)

